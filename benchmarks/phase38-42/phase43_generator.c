// Phase 43 Generator — reads multiscale weights (magic 0x53454535)
// and generates text autoregressively with multiscale_mode=1.
//
// Distribution shift fix: computes online mean/std from a warm-up window
// (first WARMUP bytes of the data file) instead of using training stats.
// Training stats are computed on a warm, 33M-byte L1; generation starts cold.
// Without online stats, the normalized features are OOD -> degenerate softmax.
//
// Usage:
//   phase43_generator.exe <data_file> <weights_file> [--gen-len N] [--temp F]
//                         [--mode argmax|sample] [--legacy] [--warmup N]
//
// Build (from repo root):
//   gcc -O3 -march=native -mavx2 -mfma \
//       benchmarks/phase38-42/phase43_generator.c \
//       src/silicon_entropy.c src/silicon_v0.c \
//       -o bin/phase43_generator.exe -lm -I .

#include <stdio.h>
#include <stdlib.h>
#include <stdint.h>
#include <string.h>
#include <math.h>
#include <time.h>
#include <immintrin.h>
#ifdef _MSC_VER
#include <intrin.h>
#else
#include <x86intrin.h>
#endif
#include "src/silicon_entropy.h"

#define CLASSES  256
#define FEAT_DIM SEE_FEATURE_DIM

static float* trigram;
static float  W[CLASSES][FEAT_DIM];
static float  B[CLASSES];
static float  feat_mean[FEAT_DIM];   // overwritten by online stats
static float  feat_std[FEAT_DIM];    // overwritten by online stats

static inline float dot_avx(const float* a, const float* b, int n) {
    __m256 acc = _mm256_setzero_ps(); int i = 0;
    for (; i <= n-8; i+=8) acc = _mm256_fmadd_ps(_mm256_loadu_ps(a+i), _mm256_loadu_ps(b+i), acc);
    float tmp[8]; _mm256_storeu_ps(tmp, acc);
    float s = tmp[0]+tmp[1]+tmp[2]+tmp[3]+tmp[4]+tmp[5]+tmp[6]+tmp[7];
    for (; i < n; i++) s += a[i]*b[i]; return s;
}

static uint8_t sample_from(const float P[CLASSES], uint64_t* rng) {
    *rng ^= *rng << 13; *rng ^= *rng >> 7; *rng ^= *rng << 17;
    double u = (*rng >> 11) * (1.0 / (1ULL << 53));
    double cum = 0;
    for (int c = 0; c < CLASSES; c++) { cum += P[c]; if (u < cum) return (uint8_t)c; }
    return 255;
}

int main(int argc, char** argv) {
    if (argc < 3) {
        fprintf(stderr, "Usage: %s <data_file> <weights_file> [opts]\n", argv[0]);
        fprintf(stderr, "  --gen-len N        bytes to generate (default 2000)\n");
        fprintf(stderr, "  --temp F           softmax temperature (default 0.7)\n");
        fprintf(stderr, "  --top-k N          top-k filtering (0=off)\n");
        fprintf(stderr, "  --rep-penalty F    logit penalty per occurrence in window (0=off)\n");
        fprintf(stderr, "  --rep-window N     repetition penalty lookback bytes (default 30)\n");
        fprintf(stderr, "  --entropy-boost F  temperature multiplier when entropy < thresh (0=off)\n");
        fprintf(stderr, "  --entropy-thresh F entropy (bits) threshold for boost (default 3.0)\n");
        fprintf(stderr, "  --mode argmax      argmax instead of sample\n");
        fprintf(stderr, "  --legacy           multiscale_mode=0\n");
        fprintf(stderr, "  --warmup N         online stats window size (default 5000)\n");
        fprintf(stderr, "  --seed-start N     byte offset in data_file for seed (default 0)\n");
        fprintf(stderr, "  --reset-interval N reset SEE state every N generated bytes (0=off)\n");
        fprintf(stderr, "  --feat-clamp F     clamp norm features to [-F,F] before readout (0=off)\n");
        fprintf(stderr, "  --rng-seed N       sampling RNG seed (default fixed -> reproducible)\n");
        return 1;
    }
    int gen_len = 2000, argmax = 0, legacy = 0;
    int warmup = 5000, seed_start = 0, top_k = 0, rep_window = 30, reset_interval = 0;
    float temp = 0.7f, rep_penalty = 0.0f, entropy_boost = 0.0f, entropy_thresh = 3.0f;
    float feat_clamp = 0.0f;
    // Fixed default => deterministic generation for identical (weights,seed_start,temp).
    // Pass --rng-seed -1 to opt back into time-based non-determinism if ever needed.
    uint64_t rng_seed = 0x243F6A8885A308D3ULL;
    int rng_seed_time = 0;
    for (int i = 3; i < argc; i++) {
        if      (!strcmp(argv[i],"--gen-len")        && i+1<argc) gen_len        = atoi(argv[++i]);
        else if (!strcmp(argv[i],"--temp")           && i+1<argc) temp           = (float)atof(argv[++i]);
        else if (!strcmp(argv[i],"--warmup")         && i+1<argc) warmup         = atoi(argv[++i]);
        else if (!strcmp(argv[i],"--seed-start")     && i+1<argc) seed_start     = atoi(argv[++i]);
        else if (!strcmp(argv[i],"--top-k")          && i+1<argc) top_k          = atoi(argv[++i]);
        else if (!strcmp(argv[i],"--rep-penalty")    && i+1<argc) rep_penalty    = (float)atof(argv[++i]);
        else if (!strcmp(argv[i],"--rep-window")     && i+1<argc) rep_window     = atoi(argv[++i]);
        else if (!strcmp(argv[i],"--entropy-boost")  && i+1<argc) entropy_boost  = (float)atof(argv[++i]);
        else if (!strcmp(argv[i],"--entropy-thresh") && i+1<argc) entropy_thresh = (float)atof(argv[++i]);
        else if (!strcmp(argv[i],"--reset-interval") && i+1<argc) reset_interval = atoi(argv[++i]);
        else if (!strcmp(argv[i],"--feat-clamp")     && i+1<argc) feat_clamp     = (float)atof(argv[++i]);
        else if (!strcmp(argv[i],"--rng-seed")       && i+1<argc) {
            const char* v = argv[++i];
            if (!strcmp(v,"-1")) rng_seed_time = 1;            // explicit opt-in to time-based
            else rng_seed = strtoull(v, NULL, 0);
        }
        else if (!strcmp(argv[i],"--mode")           && i+1<argc) argmax = !strcmp(argv[++i],"argmax");
        else if (!strcmp(argv[i],"--legacy")) legacy = 1;
    }

    // Read data file
    FILE* fd = fopen(argv[1],"rb");
    if (!fd) { fprintf(stderr,"Cannot open: %s\n",argv[1]); return 1; }
    fseek(fd,0,SEEK_END); long fsz = ftell(fd); fseek(fd,0,SEEK_SET);
    long total_needed = (long)seed_start + warmup + 512;
    if (total_needed > fsz) { total_needed = fsz; warmup = (int)(fsz - seed_start - 512); if (warmup < 0) warmup = 0; }
    uint8_t* file_data = malloc(total_needed);
    fread(file_data, 1, total_needed, fd); fclose(fd);

    // Load weights — supports five formats:
    //   0x53454531 (phase42a): {magic,ver,fdim,chunk,decay,seed,alpha,poolmode}
    //   0x53454535 (phase43a): {magic,ver,fdim,chunk} + float[3]{decay,0.1,alpha_fast}
    //   0x53454536 (phase43b): same as 535 + float[4] + byte_gain[256]
    //   0x53454537 (phase43h): {magic,ver,fdim,chunk} + float[4]{decay,0.1,alpha_fast,feat_clamp}
    //   0x53454538 (phase43c): {magic,ver,fdim,chunk} + float[5]{decay,0.1,alpha_fast,feat_clamp,eta_oja}
    //                          + W_oja[SEE_N_OJA*43]   (fixed 13 plastic cells)
    //   0x53454539 (phase43c2): {magic,ver,fdim,chunk} + float[5]{...,eta_oja}
    //                          + uint32 n_oja + W_oja[n_oja*43]  (self-describing capacity)
    //   0x5345453A (phase43c3): {magic,ver,fdim,chunk} + float[6]{...,eta_oja,plastic_blend}
    //                          + uint32 n_oja + W_oja[n_oja*43]  (homeostatic blend)
    //   0x5345453B (phase43d): same as 53A + byte_route[256*SEE_ROUTE_LANES] after W_oja
    //                          (byte-to-lane routing, geometry of writing)
    FILE* fw = fopen(argv[2],"rb");
    if (!fw) { fprintf(stderr,"Cannot open weights: %s\n",argv[2]); return 1; }
    uint32_t magic_peek; fread(&magic_peek,4,1,fw); rewind(fw);

    float   decay = 0.75f, alpha_fast = 0.5f;
    int     codebook_seed = 42;
    int     pooling_mode_hdr = 0;
    int     oja_loaded = 0;
    int     file_n_oja = SEE_N_OJA;
    float   file_eta_oja = 0.0f;
    float   file_plastic_blend = 1.0f;
    float   W_oja_buf[SEE_N_OJA_MAX * 43];
    int     route_loaded = 0;
    float   route_buf[256 * SEE_ROUTE_LANES];

    if (magic_peek == 0x53454531) {
        uint32_t h32[8]; fread(h32, 4, 8, fw);
        memcpy(&decay,  &h32[4], 4);
        codebook_seed    = (int)h32[5];
        pooling_mode_hdr = (int)h32[7];
        legacy = 1;
        fprintf(stderr,"Format: 0x53454531 (phase42a)  seed=%d  pool=%d  decay=%.3f\n",
                codebook_seed, pooling_mode_hdr, decay);
    } else if (magic_peek == 0x53454535 || magic_peek == 0x53454536) {
        uint32_t hdr4[4]; fread(hdr4, 4, 4, fw);
        int hf_count = (magic_peek == 0x53454536) ? 4 : 3;
        float hf[4]; fread(hf, 4, hf_count, fw);
        decay      = hf[0];
        alpha_fast = hf[2];
        if (magic_peek == 0x53454536) { float skip[256]; fread(skip,4,256,fw); }
        fprintf(stderr,"Format: 0x%08x  alpha_fast=%.2f  decay=%.3f  %s\n",
                magic_peek, alpha_fast, decay, legacy?"legacy":"multiscale");
    } else if (magic_peek == 0x53454537) {
        // Phase 43.H clamped: 4th float = feat_clamp
        uint32_t hdr4[4]; fread(hdr4, 4, 4, fw);
        float hf[4]; fread(hf, 4, 4, fw);
        decay      = hf[0];
        alpha_fast = hf[2];
        if (feat_clamp == 0.0f) feat_clamp = hf[3];
        fprintf(stderr,"Format: 0x53454537 (SEE-V1S)  alpha_fast=%.2f  feat_clamp=%.2f  decay=%.3f\n",
                alpha_fast, feat_clamp, decay);
    } else if (magic_peek == 0x53454538) {
        // Phase 43.C Oja: 5 floats + W_oja[SEE_N_OJA*43] before trigram.
        // W_oja is stashed in W_oja_buf and copied into `see` after see_init
        // (which would otherwise reset it to identity). Frozen for generation.
        uint32_t hdr4[4]; fread(hdr4, 4, 4, fw);
        float hf[5]; fread(hf, 4, 5, fw);
        decay      = hf[0];
        alpha_fast = hf[2];
        if (feat_clamp == 0.0f) feat_clamp = hf[3];
        file_eta_oja = hf[4];
        file_n_oja = SEE_N_OJA;   // fixed 13 in this legacy Oja format
        fread(W_oja_buf, sizeof(float), (size_t)file_n_oja * 43, fw);
        oja_loaded = 1;
        fprintf(stderr,"Format: 0x53454538 (SEE-V1S+Oja)  alpha_fast=%.2f  feat_clamp=%.2f  n_oja=%d  train_eta_oja=%.0e\n",
                alpha_fast, feat_clamp, file_n_oja, (double)file_eta_oja);
    } else if (magic_peek == 0x53454539) {
        // Phase 43.C2: self-describing plastic capacity.
        // 5 floats + uint32 n_oja + W_oja[n_oja*43] before trigram.
        uint32_t hdr4[4]; fread(hdr4, 4, 4, fw);
        float hf[5]; fread(hf, 4, 5, fw);
        decay      = hf[0];
        alpha_fast = hf[2];
        if (feat_clamp == 0.0f) feat_clamp = hf[3];
        file_eta_oja = hf[4];
        uint32_t n_oja_u = 0; fread(&n_oja_u, 4, 1, fw);
        file_n_oja = (int)n_oja_u;
        if (file_n_oja < 0 || file_n_oja > SEE_N_OJA_MAX) {
            fprintf(stderr,"Bad n_oja in header: %d (max %d)\n", file_n_oja, SEE_N_OJA_MAX);
            fclose(fw); return 1;
        }
        fread(W_oja_buf, sizeof(float), (size_t)file_n_oja * 43, fw);
        oja_loaded = 1;
        fprintf(stderr,"Format: 0x53454539 (SEE-V2.x+Oja)  alpha_fast=%.2f  feat_clamp=%.2f  n_oja=%d  train_eta_oja=%.0e\n",
                alpha_fast, feat_clamp, file_n_oja, (double)file_eta_oja);
    } else if (magic_peek == 0x5345453A) {
        // Phase 43.C3: self-describing capacity + homeostatic plastic blend.
        // 6 floats {decay,0.1,alpha_fast,feat_clamp,eta_oja,plastic_blend}
        // + uint32 n_oja + W_oja[n_oja*43] before trigram.
        uint32_t hdr4[4]; fread(hdr4, 4, 4, fw);
        float hf[6]; fread(hf, 4, 6, fw);
        decay      = hf[0];
        alpha_fast = hf[2];
        if (feat_clamp == 0.0f) feat_clamp = hf[3];
        file_eta_oja = hf[4];
        file_plastic_blend = hf[5];
        uint32_t n_oja_u = 0; fread(&n_oja_u, 4, 1, fw);
        file_n_oja = (int)n_oja_u;
        if (file_n_oja < 0 || file_n_oja > SEE_N_OJA_MAX) {
            fprintf(stderr,"Bad n_oja in header: %d (max %d)\n", file_n_oja, SEE_N_OJA_MAX);
            fclose(fw); return 1;
        }
        fread(W_oja_buf, sizeof(float), (size_t)file_n_oja * 43, fw);
        oja_loaded = 1;
        fprintf(stderr,"Format: 0x5345453A (SEE-V2.x+Oja+homeostasis)  alpha_fast=%.2f  feat_clamp=%.2f  n_oja=%d  eta=%.0e  blend=%.2f\n",
                alpha_fast, feat_clamp, file_n_oja, (double)file_eta_oja, (double)file_plastic_blend);
    } else if (magic_peek == 0x5345453B) {
        // Phase 43.D: 53A layout + byte_route[256*SEE_ROUTE_LANES] after W_oja.
        uint32_t hdr4[4]; fread(hdr4, 4, 4, fw);
        float hf[6]; fread(hf, 4, 6, fw);
        decay      = hf[0];
        alpha_fast = hf[2];
        if (feat_clamp == 0.0f) feat_clamp = hf[3];
        file_eta_oja = hf[4];
        file_plastic_blend = hf[5];
        uint32_t n_oja_u = 0; fread(&n_oja_u, 4, 1, fw);
        file_n_oja = (int)n_oja_u;
        if (file_n_oja < 0 || file_n_oja > SEE_N_OJA_MAX) {
            fprintf(stderr,"Bad n_oja in header: %d (max %d)\n", file_n_oja, SEE_N_OJA_MAX);
            fclose(fw); return 1;
        }
        fread(W_oja_buf, sizeof(float), (size_t)file_n_oja * 43, fw);
        oja_loaded = 1;
        fread(route_buf, sizeof(float), (size_t)256 * SEE_ROUTE_LANES, fw);
        route_loaded = 1;
        fprintf(stderr,"Format: 0x5345453B (SEE-V2+Oja+route)  alpha_fast=%.2f  feat_clamp=%.2f  n_oja=%d  eta=%.0e  blend=%.2f  +byte_route[256][%d]\n",
                alpha_fast, feat_clamp, file_n_oja, (double)file_eta_oja, (double)file_plastic_blend, SEE_ROUTE_LANES);
    } else {
        fprintf(stderr,"Unsupported magic: 0x%08x\n", magic_peek); fclose(fw); return 1;
    }

    size_t tri_n = (size_t)CLASSES*CLASSES*CLASSES;
    trigram = malloc(tri_n*sizeof(float));
    fread(trigram,sizeof(float),tri_n,fw);
    fread(feat_mean,sizeof(float),FEAT_DIM,fw);
    fread(feat_std, sizeof(float),FEAT_DIM,fw);
    fread(W,sizeof(float),CLASSES*FEAT_DIM,fw);
    fread(B,sizeof(float),CLASSES,fw);
    fclose(fw);

    SiliconEntropyState see;
    see_init(&see, codebook_seed, 4, decay);
    if (!legacy) {
        see.multiscale_mode = 1;
        see.alpha_fast = alpha_fast;
        see.alpha_mid  = 0.9f;
        see.alpha_slow = 0.99f;
    } else {
        see.pooling_mode = pooling_mode_hdr;
    }

    // Phase 43.C: install the trained Oja projection. Frozen (eta_oja=0) so
    // generation features match the Pass-2 re-extraction the readout trained on;
    // the learned directions are still applied because the projection is always
    // active (see see_observe). Untrained/other formats keep identity W_oja.
    if (oja_loaded) {
        // see_init already reset all SEE_N_OJA_MAX rows to identity; overwrite
        // only the first file_n_oja rows (row stride 43 matches the buffer).
        see.n_oja = file_n_oja;
        memcpy(see.W_oja, W_oja_buf, (size_t)file_n_oja * 43 * sizeof(float));
        see.eta_oja = 0.0f;
        see.plastic_blend = file_plastic_blend;   // 1.0 unless 0x5345453A (homeostasis)
        fprintf(stderr,"Oja: %d plastic cells loaded, frozen for generation (train_eta=%.0e, blend=%.2f)\n",
                file_n_oja,
                (double)file_eta_oja, (double)file_plastic_blend);
    }
    if (route_loaded) {
        memcpy(see.byte_route, route_buf, sizeof(see.byte_route));
        fprintf(stderr,"Route: byte_route[256][%d] loaded (geometry of writing)\n", SEE_ROUTE_LANES);
    }

    fprintf(stderr,"SEE: seed=%d  multiscale=%d  pool=%d\n",
            codebook_seed, see.multiscale_mode, see.pooling_mode);
    fprintf(stderr,"Warmup: %d bytes | Seed: 512 bytes | Gen: %d bytes | Temp: %.2f\n\n",
            warmup, gen_len, temp);

    // ---- Phase 1: Warmup — collect features to compute online mean/std ----
    // Process warmup bytes starting from seed_start, extract features at each step.
    // Use Welford online algorithm for numerical stability.
    double omean[FEAT_DIM], oM2[FEAT_DIM];
    memset(omean, 0, sizeof(omean));
    memset(oM2,   0, sizeof(oM2));
    long on = 0;

    see_reset(&see);
    float raw[FEAT_DIM];
    // Skip cold-start: don't sample features for first 64 bytes (L0 history barely filled)
    int cold_skip = 64;
    for (int i = seed_start; i < seed_start + warmup; i++) {
        see_observe(&see, file_data[i]);
        if (i - seed_start >= cold_skip) {
            see_extract(&see, raw);
            on++;
            for (int f=0;f<FEAT_DIM;f++) {
                double delta = raw[f] - omean[f];
                omean[f] += delta / on;
                oM2[f]   += delta * (raw[f] - omean[f]);
            }
        }
    }
    // Finalise: replace training stats with online stats
    for (int f=0;f<FEAT_DIM;f++) {
        feat_mean[f] = (float)omean[f];
        feat_std[f]  = (on > 1) ? (float)sqrt(oM2[f] / (on-1)) + 1e-8f : 1.0f;
    }
    fprintf(stderr,"Online stats computed from %ld samples (warmup=%d bytes)\n", on, warmup);

    // ---- Phase 2: Seed — condition the SEE state on 512 specific bytes ----
    // Immediately follows warmup (no reset: L1 state carries over, which is the point)
    int seed_offset = seed_start + warmup;
    int seed_len    = (int)(total_needed - seed_offset);
    if (seed_len > 512) seed_len = 512;

    uint8_t ctx2=0, ctx1=0;
    for (int i=0; i<seed_len; i++) {
        see_observe(&see, file_data[seed_offset + i]);
        if (i>0) ctx2=ctx1;
        ctx1=file_data[seed_offset+i];
    }

    // Print seed tail
    int tail_start = seed_len > 200 ? seed_len-200 : 0;
    fprintf(stderr,"--- seed tail ---\n");
    fwrite(file_data + seed_offset + tail_start, 1, seed_len - tail_start, stderr);
    fprintf(stderr,"\n--- generated ---\n");

    // ---- Phase 3: Generate ----
    // Deterministic by default: rng depends only on (rng_seed, seed_start), so
    // identical (weights, seed_start, temp, rng_seed) reproduce byte-for-byte.
    // Different generation seeds still get independent sampling streams via the
    // seed_start mix. --rng-seed -1 restores time-based non-determinism.
    uint64_t rng = rng_seed_time
        ? ((uint64_t)time(NULL) ^ 0xdeadbeefcafeULL ^ (uint64_t)seed_start)
        : (rng_seed ^ ((uint64_t)seed_start * 0x9E3779B97F4A7C15ULL));
    if (rng == 0) rng = 0x9E3779B97F4A7C15ULL;   // xorshift must not start at 0
    fprintf(stderr,"RNG: %s seed=0x%016llx (seed_start=%d)\n",
            rng_seed_time ? "time" : "fixed", (unsigned long long)rng, seed_start);
    double self_bits = 0;
    uint8_t* generated = malloc(gen_len);
    float feat[FEAT_DIM], P[CLASSES];

    for (int i=0; i<gen_len; i++) {
        // State reset diagnostic: clear L0+L1 every N bytes
        if (reset_interval > 0 && i > 0 && i % reset_interval == 0) {
            see_reset(&see);
            ctx2 = 0; ctx1 = 0;
        }

        see_extract(&see, feat);
        for (int fj=0;fj<FEAT_DIM;fj++)
            feat[fj] = (feat[fj] - feat_mean[fj]) / (feat_std[fj] + 1e-8f);

        // Feature clamp diagnostic: clip normalized features to [-F, F]
        if (feat_clamp > 0.0f) {
            for (int fj=0;fj<FEAT_DIM;fj++) {
                if (feat[fj] >  feat_clamp) feat[fj] =  feat_clamp;
                if (feat[fj] < -feat_clamp) feat[fj] = -feat_clamp;
            }
        }

        const float* tri = &trigram[(ctx2*CLASSES+ctx1)*CLASSES];
        float logits[CLASSES];
        for (int c=0;c<CLASSES;c++)
            logits[c] = (tri[c] + B[c] + dot_avx(W[c], feat, FEAT_DIM)) / temp;

        // Top-k filtering
        if (top_k > 0 && top_k < CLASSES) {
            float tmp[CLASSES]; memcpy(tmp, logits, sizeof(logits));
            float kth = -1e30f;
            for (int ki = 0; ki < top_k; ki++) {
                float best = -1e30f; int bi = -1;
                for (int c = 0; c < CLASSES; c++) if (tmp[c] > best) { best = tmp[c]; bi = c; }
                if (ki == top_k-1) kth = best;
                if (bi >= 0) tmp[bi] = -1e30f;
            }
            for (int c = 0; c < CLASSES; c++) if (logits[c] < kth) logits[c] = -1e30f;
        }

        // Repetition penalty: subtract penalty for each byte seen in last rep_window
        if (rep_penalty > 0.0f) {
            int wstart = (i >= rep_window) ? i - rep_window : 0;
            for (int w = wstart; w < i; w++)
                logits[generated[w]] -= rep_penalty;
        }

        float mx=-1e30f;
        for (int c=0;c<CLASSES;c++) if (logits[c] > mx) mx = logits[c];
        float Z=0;
        for (int c=0;c<CLASSES;c++) { P[c]=expf(logits[c]-mx); Z+=P[c]; }
        for (int c=0;c<CLASSES;c++) P[c] /= Z;

        // Entropy boost: if distribution is too peaked, raise effective temperature
        if (entropy_boost > 1.0f) {
            float H = 0;
            for (int c=0;c<CLASSES;c++) if (P[c] > 1e-30f) H -= P[c] * log2f(P[c]);
            if (H < entropy_thresh) {
                mx = -1e30f;
                for (int c=0;c<CLASSES;c++) { logits[c] /= entropy_boost; if (logits[c] > mx) mx = logits[c]; }
                Z = 0;
                for (int c=0;c<CLASSES;c++) { P[c] = expf(logits[c]-mx); Z += P[c]; }
                for (int c=0;c<CLASSES;c++) P[c] /= Z;
            }
        }

        uint8_t next;
        if (argmax) {
            float bst=-1; next=0;
            for (int c=0;c<CLASSES;c++) if (P[c]>bst) { bst=P[c]; next=(uint8_t)c; }
        } else {
            next = sample_from(P, &rng);
        }

        self_bits += -log2((double)fmaxf(P[next], 1e-30f));
        generated[i] = next;
        see_observe(&see, next);
        ctx2=ctx1; ctx1=next;

        // BPB curve: log every 100 bytes so we can see when collapse happens
        if ((i+1) % 100 == 0)
            fprintf(stderr, "bpb_at_%04d: %.4f\n", i+1, self_bits/(i+1));
    }
    fwrite(generated, 1, gen_len, stdout);

    fprintf(stderr,"\n--- stats ---\n");
    fprintf(stderr,"self_BPB: %.4f\n", self_bits/gen_len);

    free(trigram); free(file_data); free(generated);
    return 0;
}

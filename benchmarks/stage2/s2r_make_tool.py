"""Stage 2, routing by conversation: s2r_llama_score.cpp, generated from test 2b's scorer so that the panel logic stays one
text.  Adds --route-out FILE (s2r_route_hook.h).  CONFIG prints it, and a ROUTE line follows the MOE line.

Usage: python -I benchmarks/stage2/s2r_make_tool.py
"""
from pathlib import Path

HERE = Path(__file__).resolve().parent


def once(t: str, a: str, b: str) -> str:
    if t.count(a) != 1:
        raise SystemExit(f"{t.count(a)} matches: {a}")
    return t.replace(a, b)


t = (HERE / "s2t_llama_score.cpp").read_text(encoding="utf-8")
t = "// GENERATED by s2r_make_tool.py from s2t_llama_score.cpp: do not edit.\n" + t
t = once(t, '#include "s1_moe_hook.h"\n', '#include "s1_moe_hook.h"\n#include <stdexcept>\n#include "s2r_route_hook.h"\n')
t = once(t, 'else if (a == "--two-pass-k") o.two_pass_k = std::stoi(next());',
         'else if (a == "--two-pass-k") o.two_pass_k = std::stoi(next());\n        else if (a == "--route-out") o.route_out = next();')
t = once(t, "cp.cb_eval = s1::moe_cb;", "cp.cb_eval = s2r::route_cb;")
t = once(t, "cp.cb_eval_user_data = &hook;", "cp.cb_eval_user_data = &route;")
t = once(t, "    s1::MoeHook hook;\n",
         "    s1::MoeHook hook;\n    s2r::Route route;\n    route.hook = &hook;\n    route.f = fopen(o.route_out.c_str(), \"wb\");\n"
         "    if (!route.f) throw std::runtime_error(\"--route-out\");\n")
t = once(t, 'preview=%s two_pass_k=%d tail_offset=%d system_info=[%s]\\n"', 'preview=%s two_pass_k=%d tail_offset=%d route_out=%s system_info=[%s]\\n"')
t = once(t, "o.two_pass_k, o.tail_offset, llama_print_system_info());", "o.two_pass_k, o.tail_offset, o.route_out.c_str(), llama_print_system_info());")
m = "s1::print_moe(hook, positions);  // every scored position is one input token"
t = once(t, m, m + "\n    s2r::print_route(route);")
t = t.replace("std::string model, ", "std::string route_out;\n    std::string model, ", 1)
(HERE / "s2r_llama_score.cpp").write_text(t, encoding="utf-8", newline="\n")
print("ok")

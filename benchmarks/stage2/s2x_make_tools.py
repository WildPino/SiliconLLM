"""Stage 2 test 3b: s2x_llama_score.cpp and s2x_llama_generate.cpp, generated from test 2b's tools so that the panel logic
stays one text.  Adds --exact-from GGUF --exact-mode M --exact-layers L --exact-seed S (s2x_mix_hook.h).  CONFIG prints them
and a MIX line follows the MOE line.

Usage: python -I benchmarks/stage2/s2x_make_tools.py
"""
from pathlib import Path

HERE = Path(__file__).resolve().parent


def once(t: str, a: str, b: str) -> str:
    if t.count(a) != 1:
        raise SystemExit(f"{t.count(a)} matches: {a}")
    return t.replace(a, b)


def patch(tool: str, moe_print: str) -> None:
    t = (HERE / f"s2t_llama_{tool}.cpp").read_text(encoding="utf-8")
    t = "// GENERATED by s2x_make_tools.py from s2t_llama_%s.cpp: do not edit.\n" % tool + t
    t = once(t, '#include "s1_moe_hook.h"\n', '#include "s1_moe_hook.h"\n#include <omp.h>\n#include <cstring>\n#include <stdexcept>\n#include "s2x_mix_hook.h"\n')
    t = once(t, 'else if (a == "--two-pass-k") o.two_pass_k = std::stoi(next());',
             'else if (a == "--two-pass-k") o.two_pass_k = std::stoi(next());\n'
             '        else if (a == "--exact-from") o.exact_from = next();\n'
             '        else if (a == "--exact-mode") o.exact_mode = next();\n'
             '        else if (a == "--exact-layers") o.exact_layers = next();\n'
             '        else if (a == "--exact-seed") o.exact_seed = std::stoull(next());')
    t = once(t, "cp.cb_eval = s1::moe_cb;", "cp.cb_eval = o.exact_from.empty() ? s1::moe_cb : s2x::mix_cb;")
    t = once(t, "cp.cb_eval_user_data = &hook;", "cp.cb_eval_user_data = o.exact_from.empty() ? static_cast<void *>(&hook) : static_cast<void *>(&mix);")
    t = once(t, "    s1::MoeHook hook;\n",
             "    s1::MoeHook hook;\n    s2x::Mix mix;\n    mix.hook = &hook;\n    mix.mode = o.exact_mode;\n    mix.seed = o.exact_seed;\n"
             "    mix.n_threads = o.threads;\n    if (!o.exact_from.empty()) {\n"
             "        if (!s2x::valid_mode(o.exact_mode) || o.exact_layers.empty()) throw std::runtime_error(\"--exact-mode or --exact-layers\");\n"
             "        s2x::parse_layers(mix, o.exact_layers);\n        s2x::load(mix, o.exact_from);\n    }\n")
    t = once(t, 'preview=%s two_pass_k=%d tail_offset=%d system_info=[%s]\\n"',
             'preview=%s two_pass_k=%d tail_offset=%d exact_from=%s exact_mode=%s exact_layers=%s exact_seed=%llu system_info=[%s]\\n"')
    t = once(t, "o.two_pass_k, o.tail_offset, llama_print_system_info());",
             'o.two_pass_k, o.tail_offset, o.exact_from.empty() ? "-" : o.exact_from.c_str(), o.exact_mode.c_str(),\n'
             '           o.exact_layers.empty() ? "-" : o.exact_layers.c_str(), static_cast<unsigned long long>(o.exact_seed), llama_print_system_info());')
    t = once(t, moe_print, moe_print + "\n    if (!o.exact_from.empty()) s2x::print_mix(mix);")
    t = t.replace("std::string model, ", 'std::string exact_from, exact_mode = "top", exact_layers;\n    unsigned long long exact_seed = 20261104;\n    std::string model, ', 1)
    (HERE / f"s2x_llama_{tool}.cpp").write_text(t, encoding="utf-8", newline="\n")


patch("score", "s1::print_moe(hook, positions);  // every scored position is one input token")
patch("generate", "s1::print_moe(hook, input_tokens);")
print("ok")

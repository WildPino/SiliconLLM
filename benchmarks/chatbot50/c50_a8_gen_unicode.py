"""C50-A8: generate c50_unicode_tables.h (the C tokenizer's Unicode data) from Python's unicodedata.

Tables (all sorted for binary search):
- class ranges: 1 = \\p{L} (Lu Ll Lt Lm Lo), 2 = \\p{N} (Nd Nl No), 3 = White_Space (the Unicode property, which
  is what the source regex engine means by \\s), 0 = anything else;
- canonical combining class ranges (non-zero only);
- full canonical decompositions (recursive, compatibility mappings excluded; Hangul is algorithmic in C);
- primary composites: (first, second) -> composite for every two-code-point canonical decomposition whose
  composite survives NFC (this drops composition exclusions and non-starter decompositions).

Usage:
    python -I benchmarks/chatbot50/c50_a8_gen_unicode.py --out benchmarks/chatbot50/c50_unicode_tables.h
"""
from __future__ import annotations

import argparse
import unicodedata
from pathlib import Path

WHITE_SPACE = [*range(0x09, 0x0E), 0x20, 0x85, 0xA0, 0x1680, *range(0x2000, 0x200B), 0x2028, 0x2029, 0x202F,
               0x205F, 0x3000]
MAXCP = 0x110000


def ranges(vals):
    out, start = [], 0
    for cp in range(1, MAXCP + 1):
        if cp == MAXCP or vals[cp] != vals[start]:
            if vals[start]:
                out.append((start, cp - 1, vals[start]))
            start = cp
    return out


def canon(cp):
    d = unicodedata.decomposition(chr(cp))
    if not d or d.startswith("<"):
        return None
    return [int(x, 16) for x in d.split()]


def full(cp):
    d = canon(cp)
    if d is None:
        return [cp]
    return [y for x in d for y in full(x)]


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    args = ap.parse_args()
    cls = [0] * MAXCP
    ccc = [0] * MAXCP
    for cp in range(MAXCP):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        c = chr(cp)
        cat = unicodedata.category(c)
        cls[cp] = 1 if cat[0] == "L" else 2 if cat[0] == "N" else 0
        ccc[cp] = unicodedata.combining(c)
    for cp in WHITE_SPACE:
        assert cls[cp] == 0
        cls[cp] = 3
    dec, comp = [], []
    for cp in range(MAXCP):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        d = canon(cp)
        if d is None:
            continue
        dec.append((cp, full(cp)))
        if len(d) == 2 and unicodedata.normalize("NFC", chr(cp)) == chr(cp):
            comp.append((d[0], d[1], cp))
    comp.sort()
    lines = [f"/* generated by c50_a8_gen_unicode.py from Python unicodedata {unicodedata.unidata_version}; do not edit */",
             f'#define C50_UNIDATA_VERSION "{unicodedata.unidata_version}"']

    def table(name, ctype, rows, per=6):
        lines.append(f"static const {ctype} {name}[{len(rows)}] = {{")
        for i in range(0, len(rows), per):
            lines.append("    " + " ".join("{" + ",".join(str(v) for v in r) + "}," for r in rows[i:i + per]))
        lines.append("};")

    lines.append("typedef struct { uint32_t lo, hi, v; } c50_urange;")
    table("c50_ucls", "c50_urange", ranges(cls))
    table("c50_uccc", "c50_urange", ranges(ccc))
    pool, idx = [], []
    for cp, f in dec:
        idx.append((cp, len(pool), len(f)))
        pool.extend(f)
    lines.append("typedef struct { uint32_t cp, off, len; } c50_udec;")
    table("c50_udecomp", "c50_udec", idx)
    lines.append(f"static const uint32_t c50_udpool[{len(pool)}] = {{")
    for i in range(0, len(pool), 16):
        lines.append("    " + ",".join(str(v) for v in pool[i:i + 16]) + ",")
    lines.append("};")
    lines.append("typedef struct { uint32_t a, b, c; } c50_ucomp;")
    table("c50_ucompose", "c50_ucomp", comp)
    Path(args.out).write_text("\n".join(lines) + "\n", encoding="ascii")
    print("class ranges", len(ranges(cls)), "ccc ranges", len(ranges(ccc)), "decompositions", len(idx),
          "pool", len(pool), "compositions", len(comp))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
